-- Split nzb_document.files (JSONB) into normalized nzb_file + nzb_segment tables.
-- Today the segment list — including a 60-char article-id per segment — lives inside
-- the parent's JSONB column. For a 14 GB file (~20k segments) that's ~2.4 MB per row;
-- for our library of hundreds of NZBs that's hundreds of MB of JSONB. Worse, every
-- timestamp tick (`last_verified`, `health_check_enqueued_at`) rewrites the whole row
-- including the JSONB, producing massive dead-tuple bloat.
--
-- This migration only ADDS the new tables. V30 backfills from the JSONB and drops
-- the `files` column. Splitting V29/V30 makes it easier to roll back V30 in isolation
-- if the backfill's row-count assertion trips — V29 is purely additive.
--
-- Cascade behaviour mirrors what the old JSONB shape implicitly provided: deleting an
-- nzb_document drops its files; deleting a file drops its segments. Pairs cleanly with
-- EmptyNzbDocumentCleanupTask (no extra cleanup needed) and the repair handler's
-- existing deleteVirtualFiles chain.

CREATE TABLE nzb_file (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nzb_document_id BIGINT NOT NULL REFERENCES nzb_document(id) ON DELETE CASCADE,
    file_index      INT    NOT NULL,
    yenc_size       BIGINT NOT NULL,
    yenc_part_end   BIGINT
);

CREATE INDEX idx_nzb_file_document ON nzb_file(nzb_document_id);
-- Composite uniqueness on (document, file_index) catches a buggy backfill or a
-- buggy import that produces duplicate file rows for the same NZB.
CREATE UNIQUE INDEX uq_nzb_file_doc_index ON nzb_file(nzb_document_id, file_index);

CREATE TABLE nzb_segment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nzb_file_id     BIGINT NOT NULL REFERENCES nzb_file(id) ON DELETE CASCADE,
    segment_number  INT    NOT NULL,
    article_id      TEXT   NOT NULL,
    bytes           BIGINT NOT NULL
);

CREATE INDEX idx_nzb_segment_file ON nzb_segment(nzb_file_id);
